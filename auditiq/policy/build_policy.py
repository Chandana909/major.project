"""Build the policy artefacts from the clause registries.

    python policy/build_policy.py

Reads   policy/policy_v<version>.json and policy/SOP_template.md
Writes  policy/SOP_v<version>.md         (the text the agents read)
        policy/policy_parameters.sql     (clause and parameter tables)

The JSON registry is the single source for every threshold: the SOP text is
rendered from it, the controls read it, and the benchmark generator reads it.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from auditiq.policy import derive_policy, render_policy_text  # noqa: E402

VERSIONS = ["2.5", "2.6"]
# Version 2.6 exists for the policy-swap experiment. It is derived from 2.5 by
# these three changes and nothing else.
SWAP_OVERRIDES = {
    "2.1.1": {"amount_tolerance_pct": 5.0},
    "4.1.1": {"max_invoices_per_vendor_per_day": 5},
    "5.1.1": {"approval_limits": {"Manager": 150000}},
}


def derive_v26(base: dict) -> dict:
    return derive_policy(base, "2.6", "2026-04-01", SWAP_OVERRIDES)


def sql_literal(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def render_sql(policies: list[dict], sops: dict[str, str]) -> str:
    out = [
        "-- Generated by policy/build_policy.py. Do not edit by hand.",
        "-- Adds the clause registry and the clause-level parameters (feature E4).",
        "-- Additive: creates two tables and inserts the policy versions as",
        "-- INACTIVE rows. Activating a version is a separate UPDATE.",
        "",
        "CREATE TABLE IF NOT EXISTS policy_clauses (",
        "  version_number NUMERIC      NOT NULL,",
        "  clause_id      VARCHAR(20)  NOT NULL,",
        "  title          VARCHAR(200) NOT NULL,",
        "  severity       VARCHAR(10)  NOT NULL,   -- critical, high, medium, low",
        "  kind           VARCHAR(10)  NOT NULL,   -- control, judgement",
        "  PRIMARY KEY (version_number, clause_id)",
        ");",
        "",
        "CREATE TABLE IF NOT EXISTS policy_parameters (",
        "  version_number NUMERIC      NOT NULL,",
        "  clause_id      VARCHAR(20)  NOT NULL,",
        "  param_name     VARCHAR(100) NOT NULL,",
        "  param_value    JSONB        NOT NULL,",
        "  PRIMARY KEY (version_number, clause_id, param_name),",
        "  FOREIGN KEY (version_number, clause_id)",
        "    REFERENCES policy_clauses (version_number, clause_id) ON DELETE CASCADE",
        ");",
        "",
    ]
    for pol in policies:
        v = pol["version"]
        out.append(f"-- ---------- version {v} ----------")
        out.append(f"DELETE FROM policy_clauses WHERE version_number = {v};")
        for cid, clause in pol["clauses"].items():
            out.append(
                "INSERT INTO policy_clauses (version_number, clause_id, title, severity, kind) "
                f"VALUES ({v}, {sql_literal(cid)}, {sql_literal(clause['title'])}, "
                f"{sql_literal(clause['severity'])}, {sql_literal(clause['kind'])});"
            )
        for cid, clause in pol["clauses"].items():
            for name, value in clause["params"].items():
                out.append(
                    "INSERT INTO policy_parameters (version_number, clause_id, param_name, param_value) "
                    f"VALUES ({v}, {sql_literal(cid)}, {sql_literal(name)}, "
                    f"{sql_literal(json.dumps(value))}::jsonb);"
                )
        out.append(
            "INSERT INTO company_policies (policy_name, version_number, markdown_content, "
            "effective_date, is_active, updated_by)\n"
            f"SELECT {sql_literal(pol['policy_name'])}, {v}, {sql_literal(sops[v])}, "
            f"DATE {sql_literal(pol['effective_date'])}, FALSE, 'build_policy.py'\n"
            f"WHERE NOT EXISTS (SELECT 1 FROM company_policies WHERE version_number = {v});"
        )
        out.append("")
    out += [
        "-- To activate a version (one at a time):",
        "--   UPDATE company_policies SET is_active = (version_number = 2.5);",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    template = (HERE / "SOP_template.md").read_text(encoding="utf-8")
    base = json.loads((HERE / "policy_v2.5.json").read_text(encoding="utf-8"))
    v26 = derive_v26(base)
    (HERE / "policy_v2.6.json").write_text(json.dumps(v26, indent=2) + "\n", encoding="utf-8")

    policies = [base, v26]
    assert [p["version"] for p in policies] == VERSIONS
    sops = {}
    for pol in policies:
        sops[pol["version"]] = render_policy_text(pol, template)
        path = HERE / f"SOP_v{pol['version']}.md"
        path.write_text(sops[pol["version"]], encoding="utf-8", newline="\n")
        print(f"wrote {path.name} ({len(pol['clauses'])} clauses)")
    (HERE / "policy_parameters.sql").write_text(
        render_sql(policies, sops), encoding="utf-8", newline="\n"
    )
    print("wrote policy_v2.6.json, policy_parameters.sql")


if __name__ == "__main__":
    main()
