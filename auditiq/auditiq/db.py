def record_decision(db: Database, result_id: int, decision: str, reviewer: str, justification: str = "") -> None:
    """Record the reviewer's decision on a result that is waiting for review."""
    if decision not in REVIEWED:
        raise ValueError(f"decision must be one of {sorted(REVIEWED)}")
    if not reviewer.strip():
        raise ValueError("a decision needs the reviewer's name")
    if decision == "override" and not justification.strip():
        raise ValueError("an override needs a written justification")
    row = db.execute("SELECT workflow_status, audit_pack, route FROM audit_results WHERE result_id = ?",
                     (result_id,)).fetchone()
    if row is None:
        raise KeyError(f"no audit result {result_id}")
    if row["workflow_status"] != PENDING_REVIEW:
        raise ValueError(f"result {result_id} is not waiting for review ({row['workflow_status']})")
    pack = json.loads(row["audit_pack"])
    pack["review"] = {"queue": row["route"], "decision": decision, "reviewer": reviewer.strip(),
                      "justification": justification.strip(), "decided_at": now()}
    db.execute("INSERT INTO review_decisions (result_id, decision, reviewer, justification, decided_at) "
               "VALUES (?, ?, ?, ?, ?)", (result_id, decision, reviewer.strip(), justification.strip(), now()))
    db.execute("UPDATE audit_results SET workflow_status = ?, audit_pack = ? WHERE result_id = ?",
               (REVIEWED[decision], json.dumps(pack, ensure_ascii=False), result_id))
    # The decision closes the audit trail of the result.
    seq = db.scalar("SELECT COALESCE(MAX(seq), 0) + 1 FROM audit_trail WHERE result_id = ?", (result_id,))
    detail = decision + (f": {justification.strip()}" if justification.strip() else "")
    db.execute("INSERT INTO audit_trail (result_id, seq, stage, actor, detail) VALUES (?, ?, ?, ?, ?)",
               (result_id, seq, "review", reviewer.strip(), detail))
    db.commit()


# ------------------------------------------------------------------ export
def export_tables(db: Database, out: Path, tables: list[str] | None = None) -> dict[str, int]:
    """Write tables as CSV files, one per table (the embedding column is left out)."""
    out.mkdir(parents=True, exist_ok=True)
    counts = {}
    for table in tables or ALL_TABLES:
        columns = [c for c, kind in db.columns(table).items() if kind != "blob"]
        frame = db.frame(f"SELECT {', '.join(columns)} FROM {table}")
        frame.to_csv(out / f"{table}.csv", index=False, lineterminator="\n", encoding="utf-8")
        counts[table] = len(frame)
    return counts
