def load_dataset(db: Database, dataset: Path, replace: bool = True) -> dict[str, int]:
    """Load the five record tables of a dataset folder (and its labels, if present).

    With ``replace`` the ledger and everything derived from it (audit results,
    labels) are cleared first, so the database holds exactly one ledger.
    """
    dataset = Path(dataset)
    names = LEDGER_TABLES + (["labels"] if (dataset / "labels.csv").exists() else [])
    frames = {name: pd.read_csv(dataset / f"{name}.csv", dtype=str, keep_default_na=False, encoding="utf-8")
              for name in names}
    return load_frames(db, frames, dataset.name, replace=replace)


def load_frames(db: Database, frames: dict[str, pd.DataFrame], name: str, replace: bool = True) -> dict[str, int]:
    """Load the record tables of a ledger given as text frames (see ``load_dataset``); ``name`` is recorded."""
    if replace:
        for table in ["review_decisions", "audit_trail", "audit_flags", "audit_results", "audit_runs",
                      "benchmark_labels", "approval_logs", "invoices", "goods_receipts", "purchase_orders",
                      "vendor_master"]:
            db.execute(f"DELETE FROM {table}")
    counts = {}
    for source in [n for n in LEDGER_TABLES + ["labels"] if n in frames]:
        table = "benchmark_labels" if source == "labels" else source
        frame = frames[source]
        kinds = db.columns(table)
        frame = frame[[c for c in frame.columns if c in kinds]]
        rows = []
        for record in frame.itertuples(index=False):
            row = []
            for column, value in zip(frame.columns, record):
                if column in BOOLEAN_COLUMNS:
                    value = int(value.strip().lower() in ("true", "t", "1"))
                elif column in NULLABLE_REFERENCES and value == "":
                    value = None
                elif kinds[column] == "number":
                    value = float(value) if value != "" else None
                elif kinds[column] == "integer":
                    value = int(float(value)) if value != "" else None
                elif kinds[column] in ("date", "timestamp") and value == "":
                    value = None
                row.append(value)
            rows.append(row)
        marks = ", ".join("?" for _ in frame.columns)
        db.executemany(f"INSERT INTO {table} ({', '.join(frame.columns)}) VALUES ({marks})", rows)
        counts[table] = len(rows)
    db.execute("INSERT INTO meta (key, value) VALUES ('dataset', ?) "
               "ON CONFLICT (key) DO UPDATE SET value = excluded.value", (name,))
    db.commit()
    return counts


def _row(row, fields: list[str]) -> dict | None:
    if row is None:
        return None
    out = {f: row[f] for f in fields}
    if "blacklisted" in out:
        out["blacklisted"] = bool(out["blacklisted"])
    return out


_APPROVER = ("(SELECT a.{column} FROM approval_logs a WHERE a.transaction_id = i.invoice_id "
             "AND a.action_taken = 'Approved' ORDER BY a.timestamp DESC, a.log_id DESC LIMIT 1) AS {column}")


def extract_one(db: Database, invoice_id: str) -> dict | None:
    """Evidence extraction for one invoice: the invoice and every record linked to it."""
    invoice = db.execute("SELECT * FROM invoices WHERE invoice_id = ?", (invoice_id,)).fetchone()
    if invoice is None:
        return None
    po = db.execute("SELECT * FROM purchase_orders WHERE po_id = ?", (invoice["po_id"],)).fetchone()
    grn = db.execute("SELECT * FROM goods_receipts WHERE grn_id = ?", (invoice["grn_id"],)).fetchone()
    vendor = db.execute("SELECT * FROM vendor_master WHERE vendor_id = ?", (invoice["vendor_id"],)).fetchone()
    approvals = db.execute(
        "SELECT * FROM approval_logs WHERE transaction_id = ? ORDER BY timestamp, log_id", (invoice_id,)).fetchall()
    history = db.execute(
        f"SELECT {', '.join('i.' + f for f in HISTORY_FIELDS)}, {_APPROVER.format(column='approver_role')}, "
        f"{_APPROVER.format(column='approver_name')} FROM invoices i "
        "WHERE i.vendor_id = ? AND i.invoice_id <> ? ORDER BY i.date, i.invoice_id",
        (invoice["vendor_id"], invoice_id)).fetchall()
    return {
        "invoice": _row(invoice, INVOICE_FIELDS),
        "po": _row(po, PO_FIELDS),
        "grn": _row(grn, GRN_FIELDS),
        "vendor": _row(vendor, VENDOR_FIELDS),
        "approvals": [_row(a, LOG_FIELDS) for a in approvals],
        "vendor_history": [_row(h, HISTORY_FIELDS + ["approver_role", "approver_name"]) for h in history],
    }


def extract_many(db: Database, invoice_ids: list[str]) -> list[dict]:
    """Evidence extraction for a batch: the transactions `extract_one` returns, read with five queries.

    `extract_one` asks the database six questions per invoice, which is right
    for one invoice and slow for a ledger. Here the five ledger tables are read
    once and joined in memory. The history records of a vendor are shared by
    its transactions; the stages only read them.
    """
    invoices = {r["invoice_id"]: r for r in db.execute("SELECT * FROM invoices").fetchall()}
    unknown = [i for i in invoice_ids if i not in invoices]
    if unknown:
        raise KeyError(f"invoice {unknown[0]} is not in the database")
    po = {r["po_id"]: _row(r, PO_FIELDS) for r in db.execute("SELECT * FROM purchase_orders").fetchall()}
    grn = {r["grn_id"]: _row(r, GRN_FIELDS) for r in db.execute("SELECT * FROM goods_receipts").fetchall()}
    vendor = {r["vendor_id"]: _row(r, VENDOR_FIELDS) for r in db.execute("SELECT * FROM vendor_master").fetchall()}
    logs: dict[str, list] = {}
    for entry in db.execute("SELECT * FROM approval_logs ORDER BY timestamp, log_id").fetchall():
        logs.setdefault(entry["transaction_id"], []).append(entry)

    def approver(invoice_id: str) -> dict:
        approved = [e for e in logs.get(invoice_id, []) if e["action_taken"] == "Approved"]
        last = approved[-1] if approved else None
        return {"approver_role": last["approver_role"] if last else None,
                "approver_name": last["approver_name"] if last else None}

    by_vendor: dict[str, list[dict]] = {}
    for r in sorted(invoices.values(), key=lambda r: (r["date"], r["invoice_id"])):
        by_vendor.setdefault(r["vendor_id"], []).append({**_row(r, HISTORY_FIELDS), **approver(r["invoice_id"])})

    transactions = []
    for invoice_id in invoice_ids:
        r = invoices[invoice_id]
        transactions.append({
            "invoice": _row(r, INVOICE_FIELDS),
            "po": po.get(r["po_id"]),
            "grn": grn.get(r["grn_id"]),
            "vendor": vendor.get(r["vendor_id"]),
            "approvals": [_row(e, LOG_FIELDS) for e in logs.get(invoice_id, [])],
            "vendor_history": [h for h in by_vendor[r["vendor_id"]] if h["invoice_id"] != invoice_id],
        })
    return transactions


def invoice_ids(db: Database, only_unaudited: bool = False, limit: int | None = None) -> list[str]:
    sql = "SELECT i.invoice_id FROM invoices i"
    if only_unaudited:
        sql += " WHERE NOT EXISTS (SELECT 1 FROM audit_results r WHERE r.invoice_id = i.invoice_id)"
    sql += " ORDER BY i.invoice_id"
    if limit:
        sql += f" LIMIT {int(limit)}"
    return [r[0] for r in db.execute(sql)]


# ------------------------------------------------------------------ policy
def store_policy(db: Database, policy: Policy, active: bool = False) -> None:
    """Insert or replace one policy version: text, registry, clauses and parameters."""
    registry = policy.registry
    db.execute("DELETE FROM company_policies WHERE version = ?", (policy.version,))
    db.execute("INSERT INTO company_policies (version, policy_name, effective_date, markdown_content, registry, "
               "is_active) VALUES (?, ?, ?, ?, ?, 0)",
               (policy.version, registry.get("policy_name"), registry.get("effective_date"),
                policy.text, json.dumps(registry)))
    db.executemany("INSERT INTO policy_clauses (version, clause_id, title, severity, kind) VALUES (?, ?, ?, ?, ?)",
                   [(policy.version, clause_id, c["title"], c["severity"], c["kind"])
                    for clause_id, c in policy.clauses.items()])
    db.executemany("INSERT INTO policy_parameters (version, clause_id, param_name, param_value) VALUES (?, ?, ?, ?)",
                   [(policy.version, clause_id, name, json.dumps(value))
                    for clause_id, c in policy.clauses.items() for name, value in c["params"].items()])
    if active:
        set_active_policy(db, policy.version, commit=False)
    db.commit()


def set_active_policy(db: Database, version: str, commit: bool = True) -> None:
    if db.scalar("SELECT 1 FROM company_policies WHERE version = ?", (version,)) is None:
        raise KeyError(f"policy version {version} is not in the database")
    db.execute("UPDATE company_policies SET is_active = CASE WHEN version = ? THEN 1 ELSE 0 END", (version,))
    if commit:
        db.commit()


def read_policy(db: Database, version: str | None = None) -> Policy:
    """The given policy version, or the active one."""
    if version is None:
        row = db.execute("SELECT * FROM company_policies WHERE is_active = 1").fetchone()
    else:
        row = db.execute("SELECT * FROM company_policies WHERE version = ?", (version,)).fetchone()
    if row is None:
        raise KeyError("no active policy in the database" if version is None else f"no policy version {version}")
    return Policy(json.loads(row["registry"]), row["markdown_content"])


