class Row(tuple):
    """A result row readable by position and by column name, on both backends."""

    def __new__(cls, values, names):
        row = super().__new__(cls, values)
        row._names = names
        return row

    def __getitem__(self, key):
        if isinstance(key, str):
            return tuple.__getitem__(self, self._names.index(key))
        return tuple.__getitem__(self, key)

    def keys(self):
        return list(self._names)


class Database:
    """One connection to the store. SQL is written once, with ``?`` placeholders."""

    def __init__(self, raw, backend: str, target: str):
        self.raw, self.backend, self.target = raw, backend, target

    # -- statements ---------------------------------------------------------
    def _sql(self, sql: str) -> str:
        return sql if self.backend == "sqlite" else sql.replace("%", "%%").replace("?", "%s")

    def execute(self, sql: str, params: tuple | list = ()):
        return self.raw.execute(self._sql(sql), tuple(params))

    def executemany(self, sql: str, rows: list) -> None:
        if not rows:
            return
        if self.backend == "sqlite":
            self.raw.executemany(sql, rows)
        else:
            with self.raw.cursor() as cursor:
                cursor.executemany(self._sql(sql), rows)

    def insert(self, sql: str, params: tuple | list, key: str) -> int:
        """Run an INSERT and return the generated value of the column ``key``."""
        if self.backend == "sqlite":
            return self.raw.execute(sql, tuple(params)).lastrowid
        return self.raw.execute(self._sql(sql) + f" RETURNING {key}", tuple(params)).fetchone()[0]

    def scalar(self, sql: str, params: tuple | list = ()):
        row = self.execute(sql, params).fetchone()
        return None if row is None else row[0]

    def frame(self, sql: str, params: tuple | list = ()) -> pd.DataFrame:
        cursor = self.execute(sql, params)
        columns = [d[0] for d in cursor.description]
        return pd.DataFrame([tuple(r) for r in cursor.fetchall()], columns=columns)

    def commit(self) -> None:
        self.raw.commit()

    def rollback(self) -> None:
        self.raw.rollback()

    def close(self) -> None:
        self.raw.close()

    # -- catalogue ----------------------------------------------------------
    def columns(self, table: str) -> dict[str, str]:
        """Column name -> kind (text, integer, number, date, timestamp, blob) of a table or view."""
        if self.backend == "sqlite":
            declared = {r["name"]: (r["type"] or "TEXT").upper() for r in self.raw.execute(f"PRAGMA table_info({table})")}
        else:
            declared = {r[0]: r[1].upper() for r in self.execute(
                "SELECT column_name, data_type FROM information_schema.columns "
                "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position", (table,))}

        def kind(name: str, type_name: str) -> str:
            if any(t in type_name for t in ("NUMERIC", "REAL", "DOUBLE")):
                return "number"
            if "INT" in type_name:
                return "integer"
            if "TIMESTAMP" in type_name:
                return "timestamp"
            if type_name == "DATE":
                return "date"
            if type_name in ("BLOB", "BYTEA"):
                return "blob"
            return "text"
        return {name: kind(name, type_name) for name, type_name in declared.items()}

    def relations(self) -> set[str]:
        """Names of all tables and views of the schema in use."""
        if self.backend == "sqlite":
            rows = self.raw.execute("SELECT name FROM sqlite_master WHERE type IN ('table', 'view')")
        else:
            rows = self.execute("SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema()")
        return {r[0].lower() for r in rows}


def default_target() -> str:
    """Where the store is: AUDITIQ_DATABASE_URL, else the SQLite file in AUDITIQ_DB, else the default file."""
    load_env()
