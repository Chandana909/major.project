"""E-mail triage against the answer key of generated mailboxes.

    python -m evaluation.triage_eval                  results/triage/triage.md and triage.json

For each ledger, the vendor correspondence is generated (auditiq_bench/correspondence.py, seed 7, with its labels:
the category of every e-mail and whether it is a payment-redirection attempt from a look-alike domain), stored in a
new store holding the ledger (as the e-mail worker stores it), and triaged (auditiq/triage.py). Measured:

    category     the triage's category against the generator's, as a confusion matrix
    redirection  e-mails triaged high risk against the look-alike requests: true and false positives, misses
    callback     the genuine bank-detail changes (from the vendor's own domain) the triage sends for confirmation
    holds        invoices the triage would hold, and whether each is the subject of a look-alike request

The generator writes each kind of e-mail from fixed templates and makes a look-alike domain in one of four ways, so
agreement here shows that the rules do what they say on this mailbox; real mail has other wording, other tricks
(a compromised genuine account sends from the right domain) and needs its own evaluation.
"""
from __future__ import annotations

import json
import shutil
import tempfile
import time
from collections import Counter
from pathlib import Path

from auditiq import db, triage
from auditiq.policy import PROJECT_ROOT, load_policy
from auditiq_bench import correspondence

DATA = PROJECT_ROOT / "data"
OUT = PROJECT_ROOT / "results" / "triage"
LEDGERS = ["bench_seed_101", "bench_seed_202", "collusion_seed_707", "final_seed_2025"]


def evaluate(name: str, folder: Path) -> dict:
    messages, labels = correspondence.generate(DATA / name, seed=7)
    box = folder / f"{name}.mbox"
    correspondence.write(messages, labels, box)
    target = folder / f"{name}.db"
    conn = db.connect(target)
    try:
        db.load_dataset(conn, DATA / name)
        db.store_policy(conn, load_policy("2.5"), active=True)
        started = time.perf_counter()
        stored = triage.load_mailbox(conn, box)
        store_seconds = time.perf_counter() - started
        started = time.perf_counter()
        found = triage.triage_store(conn, limit=10 ** 9)
        triage_seconds = time.perf_counter() - started
    finally:
        conn.close()
    judged = {j["message_id"]: j for j in found["recent"]}
    confusion: Counter = Counter()
    tp = fp = fn = 0
    callback = callback_total = 0
    false_alarms, misses = [], []
    for label in labels:
        j = judged[label["message_id"]]
        confusion[(label["category"], j["category"])] += 1
        bec = bool(label["suspicious"])
        if j["risk"] == "high" and bec:
            tp += 1
        elif j["risk"] == "high":
            fp += 1
            false_alarms.append(label["message_id"])
        elif bec:
            fn += 1
            misses.append(label["message_id"])
        if label["category"] == "bank_change" and not bec:
            callback_total += 1
            callback += j["risk"] == "medium"
    right = sum(n for (a, b), n in confusion.items() if a == b)
    bec_invoices = {label["invoice_id"] for label in labels if label["suspicious"]}
    holds = {h["invoice_id"] for h in found["holds"]}
    return {"ledger": name, "emails": len(labels), "stored": stored, "linked": found["linked"],
            "category_accuracy": round(right / len(labels), 4),
            "confusion": {f"{a} -> {b}": n for (a, b), n in sorted(confusion.items())},
            "redirection": {"attempts": tp + fn, "true_positives": tp, "false_positives": fp, "missed": fn,
                            "precision": round(tp / (tp + fp), 4) if tp + fp else None,
                            "recall": round(tp / (tp + fn), 4) if tp + fn else None,
                            "false_alarms": false_alarms[:10], "misses": misses[:10]},
            "callback": {"genuine_bank_changes": callback_total, "sent_for_confirmation": callback},
            "holds": {"invoices": len(holds), "of_attempts": len(holds & bec_invoices),
                      "amount": found["hold_amount"]},
            "by_risk": found["by_risk"],
            "seconds": {"store": round(store_seconds, 1), "triage": round(triage_seconds, 2)}}


def render(report: dict) -> str:
    lines = ["# E-mail triage against the answer key of generated mailboxes", "",
             f"Generated by `python -m evaluation.triage_eval` on {report['date']}. The generator writes each kind of "
             "e-mail from fixed templates: agreement shows that the rules do what they say on this mailbox, not how "
             "they read real mail.", "",
             "| Ledger | E-mails | Category right | Redirection attempts | Caught | False alarms | Genuine bank changes "
             "sent for confirmation | Invoices held | Triage time |", "|---|---|---|---|---|---|---|---|---|"]
    for e in report["ledgers"]:
        r, c = e["redirection"], e["callback"]
        lines.append(f"| {e['ledger']} | {e['emails']:,} | {e['category_accuracy']:.1%} | {r['attempts']} | "
                     f"{r['true_positives']} | {r['false_positives']} | {c['sent_for_confirmation']} of "
                     f"{c['genuine_bank_changes']} | {e['holds']['invoices']} (all attempts: "
                     f"{'yes' if e['holds']['of_attempts'] == e['holds']['invoices'] else 'no'}) | {e['seconds']['triage']} s |")
    lines += ["", "Confusion of the categories (generator -> triage), all ledgers:", ""]
    total: Counter = Counter()
    for e in report["ledgers"]:
        total.update(e["confusion"])
    lines += [f"- {k}: {n:,}" for k, n in sorted(total.items())]
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    folder = Path(tempfile.mkdtemp(prefix="triage_eval_"))
    try:
        ledgers = []
        for name in LEDGERS:
            print(f"triaging the mailbox of {name}")
            ledgers.append(evaluate(name, folder))
    finally:
        shutil.rmtree(folder, ignore_errors=True)
    report = {"date": time.strftime("%Y-%m-%d"), "seed": 7, "ledgers": ledgers}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "triage.json").write_text(json.dumps(report, indent=1) + "\n", encoding="utf-8")
    (OUT / "triage.md").write_text(render(report), encoding="utf-8", newline="\n")
    print(f"wrote {OUT / 'triage.md'}")


if __name__ == "__main__":
    main()
