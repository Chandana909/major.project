"""Evaluation subset and datasheet of a generated dataset.

The evaluation subset is the part of a ledger that the LLM configurations
audit. A ledger has thousands of invoices and most are ordinary; auditing all
of them with several model calls each would spend nearly all the budget on
invoices that say nothing new. The subset keeps every invoice that matters for
the evaluation and a random sample of the rest, with a weight per invoice so
that rates computed on the subset estimate rates on the whole ledger:

    anomalous            every anomalous invoice                      weight 1
    hard_negative        every hard negative                          weight 1
    duplicate_original   every clean invoice that a duplicate copies  weight 1
    ordinary             a random sample of the other clean invoices  weight N / n

The weights of a subset sum to the number of invoices in the ledger.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from .taxonomy import CLASSES, HARD_NEGATIVE_TYPES


def evaluation_subset(labels: pd.DataFrame, n_ordinary: int, rng: np.random.Generator) -> pd.DataFrame:
    """Rows (invoice_id, stratum, weight) of the evaluation subset, ordered by invoice id."""
    originals = set(labels["related_invoice_id"]) - {""}
    stratum = labels["label"].map({"anomalous": "anomalous", "hard_negative": "hard_negative"})
    stratum = stratum.where(stratum.notna(), "ordinary")
    stratum = stratum.where(~labels["invoice_id"].isin(originals) | (labels["label"] != "clean"), "duplicate_original")
    frame = pd.DataFrame({"invoice_id": labels["invoice_id"], "stratum": stratum})
    ordinary = sorted(frame.loc[frame["stratum"] == "ordinary", "invoice_id"])
    n = min(n_ordinary, len(ordinary))
    sampled = {ordinary[int(i)] for i in rng.choice(len(ordinary), size=n, replace=False)} if n else set()
    keep = frame[(frame["stratum"] != "ordinary") | frame["invoice_id"].isin(sampled)].copy()
    keep["weight"] = np.where(keep["stratum"] == "ordinary", len(ordinary) / n if n else 0.0, 1.0)
    return keep.sort_values("invoice_id").reset_index(drop=True)


def datasheet(name: str, purpose: str, manifest: dict, tables: dict[str, pd.DataFrame], policy: dict) -> str:
    """The README of a dataset folder, written from the generated tables."""
    labels, subset = tables["labels"], tables["eval_subset"]
    counts = manifest["counts"]
    ledger = ["vendor_master", "purchase_orders", "goods_receipts", "invoices", "approval_logs"]
    total = sum(len(tables[t]) for t in ledger)
    lines = [
        f"# Dataset `{name}`",
        "",
        purpose,
        "",
        f"Generated by `python -m auditiq_bench --only {name}` (generator {manifest['generator_version']}, "
        f"seed {manifest['seed']}, policy v{manifest['policy_version']}). The same command gives byte-identical "
        "files; `manifest.json` holds their SHA-256 hashes. Everything is synthetic: no vendor, person or "
        "invoice is real.",
        "",
        "## Files",
        "",
        "| File | Rows | Content |",
        "|---|---|---|",
        f"| `vendor_master.csv` | {len(tables['vendor_master']):,} | one row per vendor: name, GSTIN, category, blacklist flag, registration status |",
        f"| `purchase_orders.csv` | {len(tables['purchase_orders']):,} | what was ordered: amount, quantity, unit price, description |",
        f"| `goods_receipts.csv` | {len(tables['goods_receipts']):,} | what was received against a PO: quantities and the receiver's remarks |",
        f"| `invoices.csv` | {len(tables['invoices']):,} | what the vendor billed, with its PO and GRN references |",
        f"| `approval_logs.csv` | {len(tables['approval_logs']):,} | who forwarded or approved each invoice, with role and time |",
        f"| `labels.csv` | {len(labels):,} | ground truth of every invoice; never read by the pipeline |",
        f"| `eval_subset.csv` | {len(subset):,} | the invoices the LLM configurations audit, with weights |",
        "| `manifest.json` | | seed, versions, counts, file hashes |",
        "",
        f"The five record tables hold {total:,} records. Their columns are described in "
        "`docs/DATA_DICTIONARY.md`; they load into the database with `python -m auditiq setup --dataset <folder>`.",
        f"Invoices are dated {manifest['period'][0]} to {manifest['period'][1]}.",
        "",
        "## Ground truth",
        "",
        f"{counts['anomalous']:,} of the {counts['invoices']:,} invoices are anomalous "
        f"({counts['anomalous'] / counts['invoices']:.1%}), {counts['hard_negative']:,} are hard negatives "
        f"and {counts['clean']:,} are ordinary clean invoices.",
        "",
        "| Class | Anomaly | Rule(s) | Decided by | Severity | Invoices |",
        "|---|---|---|---|---|---|",
    ]
    for class_id, c in CLASSES.items():
        n = int((labels["class_id"] == class_id).sum())
        if n == 0:
            continue
        severities = sorted({policy["clauses"][k]["severity"] for k in c.clauses})
        decided = "a control" if c.kind == "rule" else "an agent"
        lines.append(f"| {class_id} | {c.name} | {', '.join(c.clauses)} | {decided} | {' or '.join(severities)} | {n} |")
    negatives = [(h, int((labels["hard_negative_type"] == h).sum())) for h in HARD_NEGATIVE_TYPES]
    if any(n for _, n in negatives):
        lines += ["", "Hard negatives are clean invoices built to resemble an anomaly:", "",
                  "| Type | Description | Invoices |", "|---|---|---|"]
        lines += [f"| {h} | {HARD_NEGATIVE_TYPES[h]} | {n} |" for h, n in negatives if n]
    if "alt_policy_version" in manifest:
        lines += ["", f"Every anomalous invoice of this dataset is clean under policy v{manifest['alt_policy_version']} "
                      "(`alt_label` in `labels.csv`), and every other invoice is clean under both versions."]
    lines += [
        "",
        "`labels.csv` columns: `invoice_id`; `label` (clean, hard_negative, anomalous); `class_id`; `clause_ids` "
        "(the violated rules, separated by `|`); `severity`; `group_id` (invoices that form one case, such as a "
        "same-day group); `related_invoice_id` (the original that a duplicate copies); `hard_negative_type`; "
        "`note` (what was injected, in words).",
        "",
        "## Evaluation subset",
        "",
        "| Stratum | Invoices | Weight |",
        "|---|---|---|",
    ]
    for stratum, group in subset.groupby("stratum", sort=False):
        lines.append(f"| {stratum} | {len(group):,} | {group['weight'].iloc[0]:.3f} |")
    lines += [
        "",
        f"The weights sum to {subset['weight'].sum():,.0f}, the number of invoices. The controls and the classical "
        "detectors are evaluated on the whole ledger; the LLM configurations audit this subset, with the whole "
        "ledger as the vendor history, and their rates are computed with the weights.",
        "",
    ]
    return "\n".join(lines)
